sobrenome = []
sobrenome.append("correa")
# .append vai incluir sempre no final da lista 

sobrenome.insert(0, "Silva")
# .insert inclui na posição que você que você informa com o numero do indice

print(sobrenome)

sobrenome.remove ("correa")
# .remove remove da lista o que você coloca entre parentes

del sobrenome[0]
print(sobrenome)
# del remove da lista pelo indice (o numero que corresponde ao local que está no texto)